import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const readJSON = name => JSON.parse(fs.readFileSync(path.join(root, name), 'utf8'));
export const sourceKindNames = {
  'company-sample': 'Company-published sample or historical hiring task',
  'official-practice': 'Official public practice problem',
  'documentation-derived': 'Original exercise derived from official documentation'
};
const provenance = {
  'company-sample': 'A public company sample or historical assignment. The worked example is a preparation exercise; publication does not establish current hiring use.',
  'official-practice': 'A practice problem published by the named organization. The worked explanation is an editorial preparation aid; contest or course publication does not establish hiring use.',
  'documentation-derived': 'An original preparation exercise based on the cited official technical source. It is not a published company interview question.'
};
export const companySlug = company => company.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const number = n => String(n).padStart(2, '0');
const table = value => String(value).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const anchor = id => id.replace(':', '-');
const conceptLink = (node, prefix = '') => `[${node.label}](${prefix}KNOWLEDGE_MAP.md#${anchor(node.id)})`;
const questionLink = (question, prefix = '') => `[${question.title}](${prefix}questions/${companySlug(question.company)}.md#question-${question.id})`;
const chapterLinks = (chapters, prefix) => chapters.map(chapter =>
  `[Original chapter ${number(chapter)}](${prefix}chapters/${number(chapter)}.md) · [English lesson ${number(chapter)}](https://zhiyuan-deng.pages.dev/dictionary/reader#chapter-${number(chapter)})`).join('\n\n');
const jsonBlock = value => '```json\n' + JSON.stringify(value, null, 2) + '\n```';
const generated = '<!-- Generated by scripts/english-interviews.mjs from data/english/. -->\n\n';

export function loadEnglishInterviews() {
  const manifest = readJSON('data/english/manifest.json');
  const batches = manifest.batches.map(batch => ({...batch, questions: readJSON(`data/english/${batch.file}`)}));
  const questions = batches.flatMap(batch => batch.questions);
  const graph = readJSON(`data/english/${manifest.knowledgeMap}`);
  return {manifest, batches, questions, graph};
}

export function buildEnglishInterviews(emit) {
  const {manifest, batches, questions, graph} = loadEnglishInterviews();
  const areas = graph.nodes.filter(node => node.type === 'area');
  const concepts = graph.nodes.filter(node => node.type === 'concept');
  const byId = new Map(graph.nodes.map(node => [node.id, node]));
  const companies = [...new Set(questions.map(question => question.company))].sort((a, b) => a.localeCompare(b, 'en'));
  const sourceCounts = Object.fromEntries(Object.keys(sourceKindNames).map(kind => [kind, questions.filter(question => question.sourceKind === kind).length]));
  const sourceTable = '| Source type | Entries |\n| --- | ---: |\n' + Object.entries(sourceKindNames).map(([kind, label]) => `| ${label} | ${sourceCounts[kind]} |`).join('\n');
  const evidence = `Reviewed **${manifest.reviewedAt}**. Source publication does not establish current hiring use. Company samples, public practice problems, and documentation-derived exercises have separate provenance labels.\n\n${sourceTable}\n\n`;
  const navigation = '[English overview](README.md) · [Question index](INTERVIEW_QUESTIONS.md) · [Complete knowledge map](KNOWLEDGE_MAP.md)';
  const notes = manifest.sourceNotes.map(file => `- [${file.replace(/^dictionary-interviews-/, '').replace(/\.md$/, '').replaceAll('-', ' ')}](sources/${file})`).join('\n');

  emit('docs/en/README.md', generated + '# CS and AI: English Interview Preparation\n\n' +
    `**${questions.length} English preparation entries, ${questions.reduce((sum, question) => sum + question.examples.length, 0)} worked examples, ${concepts.length} concepts, and ${areas.length} subject areas.**\n\n` +
    'Start with the complete area map, choose a subject, then open a linked question. Each question includes its source, input/output examples, reasoning, answer, complexity, pitfalls, and related concepts.\n\n' +
    `${navigation}\n\n` + evidence +
    '## Collections and language\n\n' +
    `The repository contains **100 sourced preparation entries**: [36 original entries](../INTERVIEW_QUESTIONS.md) and [64 English supplement entries](INTERVIEW_QUESTIONS.md). The original collection and chapter files retain their original Chinese or bilingual text. The English supplement and this ${concepts.length}-concept map are readable directly on GitHub.\n\n` +
    '[Interactive English dictionary](https://zhiyuan-deng.pages.dev/dictionary/#home) · [Interactive English map](https://zhiyuan-deng.pages.dev/dictionary/knowledge-map) · [English reader](https://zhiyuan-deng.pages.dev/dictionary/reader)\n\n' +
    '## Company directory\n\n' + companies.map(company => `- [${company}](questions/${companySlug(company)}.md) (${questions.filter(question => question.company === company).length})`).join('\n') + '\n\n' +
    '## Source review notes\n\n' + notes + '\n\n' +
    '## Reproducible content snapshot\n\n' +
    `- English content: [personal website commit ${manifest.sourceRevision.slice(0, 7)}](${manifest.sourceRepository}/commit/${manifest.sourceRevision}).\n` +
    `- Original dictionary base: [commit ${manifest.baseDictionaryRevision.slice(0, 7)}](https://github.com/DengZhiyuan-math/dictionary-of-computer-science-and-AI/commit/${manifest.baseDictionaryRevision}).\n` +
    '- Edit the JSON files in `data/english/`, then run `npm run build` and `npm run check`. Generated Markdown belongs to the same versioned snapshot as the JSON.\n');

  let index = generated + '# English Interview Preparation: Question Index\n\n' +
    `${questions.length} entries across ${companies.length} organizations. Each link opens a complete question in its company page.\n\n${navigation}\n\n` + evidence +
    'The [36 original entries](../INTERVIEW_QUESTIONS.md) remain available in their original language; the combined catalog contains 100 entries.\n\n' +
    '## Company directory\n\n| Organization | Entries |\n| --- | ---: |\n' +
    companies.map(company => `| [${company}](questions/${companySlug(company)}.md) | ${questions.filter(question => question.company === company).length} |`).join('\n') + '\n\n';
  for (const batch of batches) {
    index += `## ${batch.title}\n\n| Question | Organization | Source type | Related concepts |\n| --- | --- | --- | --- |\n`;
    for (const question of batch.questions) index += `| ${table(questionLink(question))} | ${question.company} | ${sourceKindNames[question.sourceKind]} | ${question.topics.map(key => table(conceptLink(byId.get(`concept:${key}`)))).join(', ')} |\n`;
    index += '\n';
  }
  emit('docs/en/INTERVIEW_QUESTIONS.md', index);

  for (const company of companies) {
    const selected = questions.filter(question => question.company === company);
    let text = generated + `# ${company}: Public Interview Preparation\n\n` +
      `${selected.length} preparation entries. Reviewed **${manifest.reviewedAt}**. Source publication does not establish current hiring use; each entry states its evidence category.\n\n` +
      '[English overview](../README.md) · [All questions](../INTERVIEW_QUESTIONS.md) · [Complete map](../KNOWLEDGE_MAP.md)\n\n' +
      selected.map(question => `- [${question.title}](#question-${question.id})`).join('\n') + '\n\n';
    for (const question of selected) {
      text += `<a id="question-${question.id}"></a>\n\n## ${question.title}\n\n` +
        `**Source type:** ${sourceKindNames[question.sourceKind]}\n\n` +
        `**Primary source:** [${question.sourceTitle}](${question.url})\n\n**Checked:** ${question.checked}\n\n` +
        `**Provenance and scope:** ${question.sourceNote || provenance[question.sourceKind]}\n\n`;
      if (question.additionalSources?.length) text += '**Additional sources:**\n\n' + question.additionalSources.map(source => `- [${source.title}](${source.url})`).join('\n') + '\n\n';
      text += `### Problem\n\n${question.prompt.replaceAll('A[i](i−l+1)', '`A[i](i−l+1)`')}\n\n### Approach\n\n` +
        question.approach.map((step, i) => `${i + 1}. ${step}`).join('\n') +
        `\n\n### Worked examples\n\n`;
      for (const [i, example] of question.examples.entries()) text += `#### Example ${i + 1}\n\n**Input**\n\n${jsonBlock(example.input)}\n\n**Output**\n\n${jsonBlock(example.output)}\n\n${example.explanation}\n\n`;
      text += `### Answer\n\n${question.answer}\n\n### Complexity\n\n${question.complexity}\n\n### Pitfalls\n\n` +
        question.pitfalls.map(pitfall => `- ${pitfall}`).join('\n') +
        `\n\n### Follow-up\n\n${question.followUp}\n\n### Related knowledge\n\n` +
        question.topics.map(key => `- ${conceptLink(byId.get(`concept:${key}`), '../')}`).join('\n') +
        '\n\n### Background reading\n\nOriginal chapter links below lead to the original Chinese or bilingual text. The paired live lessons are in English.\n\n' +
        chapterLinks(question.chapters, '../../../') + '\n\n---\n\n';
    }
    emit(`docs/en/questions/${companySlug(company)}.md`, text);
  }

  let map = generated + '# Complete CS and AI Knowledge Map\n\n' +
    `**${areas.length} areas → ${concepts.length} concepts → ${questions.length} English preparation entries.** Start with the complete area overview, then follow a subject or concept link.\n\n${navigation}\n\n` +
    `Reviewed **${manifest.reviewedAt}**. This is the full English concept map, including foundations that support the interview exercises. The [question index](INTERVIEW_QUESTIONS.md) preserves the provenance of each exercise.\n\n` +
    '## Complete area overview\n\n| Area | Layer | Concepts | Guiding question |\n| --- | --- | ---: | --- |\n' +
    areas.map(area => `| [${table(area.label)}](#${anchor(area.id)}) | ${table(area.layer)} | ${concepts.filter(concept => concept.area === area.area).length} | ${table(area.question)} |`).join('\n') + '\n\n' +
    'Prerequisite arrows run from the foundation to the concept that uses it. Related-area links are recommended connections, rather than strict requirements.\n\n';
  for (const area of areas) {
    const selected = concepts.filter(concept => concept.area === area.area);
    const connections = graph.edges.filter(edge => edge.from === area.id && byId.get(edge.to)?.type === 'area');
    map += `<a id="${anchor(area.id)}"></a>\n\n### ${area.label}\n\n${area.description}\n\n**Guiding question:** ${area.question}\n\n` +
      (selected.length ? selected.map(concept => `- ${conceptLink(concept)}`).join('\n') : '- [Open the question bank](INTERVIEW_QUESTIONS.md) and follow its linked concepts in the subject areas above.') + '\n\n';
    if (connections.length) map += '**Related areas:** ' + connections.map(edge => `[${byId.get(edge.to).label}](#${anchor(edge.to)})`).join(' · ') + '\n\n';
  }
  map += '## Concept explanations\n\n';
  for (const area of areas) for (const concept of concepts.filter(node => node.area === area.area)) {
    const prerequisites = graph.edges.filter(edge => edge.type === 'prerequisite' && edge.to === concept.id).map(edge => byId.get(edge.from));
    const next = graph.edges.filter(edge => edge.type === 'prerequisite' && edge.from === concept.id).map(edge => byId.get(edge.to));
    const related = graph.edges.filter(edge => !['contains', 'prerequisite'].includes(edge.type) && (edge.from === concept.id || edge.to === concept.id))
      .map(edge => ({node: byId.get(edge.from === concept.id ? edge.to : edge.from), edge}));
    const practice = questions.filter(question => question.topics.includes(concept.key));
    map += `<a id="${anchor(concept.id)}"></a>\n\n### ${concept.label}\n\n` +
      `**Area:** [${area.label}](#${anchor(area.id)})\n\n**Definition:** ${concept.description}\n\n` +
      (concept.explanation?.length ? '**Explanation:**\n\n' + concept.explanation.join('\n\n') + '\n\n' : '') +
      `**Boundary and distinctions:** ${concept.boundary}\n\n` +
      '**Recommended prerequisites:** ' + (prerequisites.length ? prerequisites.map(node => conceptLink(node)).join(' · ') : 'No explicit prerequisite edge in this map.') + '\n\n';
    if (next.length) map += '**Supports these next concepts:** ' + next.map(node => conceptLink(node)).join(' · ') + '\n\n';
    if (related.length) map += '**Related connections:**\n\n' + related.map(({node, edge}) => `- ${conceptLink(node)} — ${edge.label}`).join('\n') + '\n\n';
    if (concept.url) map += `**Official reference:** [Technical source](${concept.url})\n\n`;
    map += '**Related English questions:**\n\n' + (practice.length ? practice.map(question => `- ${questionLink(question)}`).join('\n') : 'No English supplement question is assigned to this concept yet.') + '\n\n' +
      '**Background reading:** Original chapters retain Chinese or bilingual text; paired live lessons are in English.\n\n' + chapterLinks(concept.chapters, '../../') + '\n\n---\n\n';
  }
  emit('docs/en/KNOWLEDGE_MAP.md', map);
}
