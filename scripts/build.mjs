import fs from 'node:fs';
import path from 'node:path';
import {root, read, book, glossary, hot100, clean, markdown, chapterText} from './model.mjs';
import {buildKnowledgeMap} from './knowledge-map.mjs';

const outputs = new Map();
const emit = (name, value) => outputs.set(name, value.replace(/\r\n/g, '\n').trimEnd() + '\n');
const generated = '<!-- Generated by node scripts/build.mjs. Edit data/book.json or data/glossary.json. -->\n\n';
const knowledgeGraph=buildKnowledgeMap(emit);
const mapTemplate=read('src/knowledge-map.html');
if(mapTemplate.split('__KNOWLEDGE_GRAPH__').length!==2)throw new Error('Expected one knowledge graph placeholder');
emit('docs/knowledge-map.html',mapTemplate.replace('__KNOWLEDGE_GRAPH__',()=>JSON.stringify(knowledgeGraph).replace(/</g,'\\u003c')));
const toc = book.chapters.map(c => `- [第 ${c.num} 讲：${c.title}](#chapter-${c.num})`).join('\n');
emit('cs_ai_v2_full.md', generated + `# dictionary of computer science and AI\n\n计算机科学与现代 AI：${book.stats.chapters} 讲通识笔记 · v${book.metadata.version}\n\n版本日期：${book.metadata.date}。原稿 v2 的 80 讲与 90 道口述题保持完整，追加 Hot 100 的 17 讲；当前含 ${book.stats.new_subsections} 个细讲小节。\n\n` +
  '面向入门学习、技术交流和基础面试。先理解问题、输入输出、方法与适用边界，再学习公式和实现。“重点精学”代表值得继续深入，不代表第一次阅读就要掌握推导。\n\n' +
  '这份通识笔记不穷尽所有 CS 分支，也不作为最新模型排行榜。口述参考答案应结合自己的真实经历。播放器使用浏览器或系统语音，不包含预录 MP3；离线语音与后台播放取决于设备。\n\n' +
  '[知识地图](docs/KNOWLEDGE_MAP.md) · [学习路线](docs/LEARNING_PATHS.md) · [术语词典](docs/GLOSSARY.md) · [小节索引](cs_ai_v2_index.md) · [训练速查](docs/TRAINING_CHEATSHEET.md) · [Hot 100 算法思想](docs/LEETCODE_HOT100.md) · [全部参考资料](docs/REFERENCES.md)\n\n## 目录\n\n' + toc + '\n\n---\n\n' + book.chapters.map(markdown).join('\n\n---\n\n'));

for (const c of book.chapters) {
  const links = [c.id > 0 ? `[← 第 ${book.chapters[c.id-1].num} 讲](${book.chapters[c.id-1].num}.md)` : null, '[目录](../cs_ai_v2_index.md)', '[术语词典](../docs/GLOSSARY.md)', c.id + 1 < book.chapters.length ? `[第 ${book.chapters[c.id+1].num} 讲 →](${book.chapters[c.id+1].num}.md)` : null].filter(Boolean).join(' · ');
  emit(`chapters/${c.num}.md`, generated + links + '\n\n' + markdown(c) + '\n\n---\n\n' + links);
  emit(`text/chapters/${c.num}.txt`, chapterText(c));
}
emit('text/cs_ai_v2_full.txt', book.chapters.map(chapterText).join('\n\n'));

const micro = book.microOrder.map(id => book.chapters[id]);
emit('cs_ai_v2_training_terms.md', generated + '# 训练微知识点：从数据到评价\n\n10 讲正文与 20 道口述追问。编号沿用完整讲稿，内容与播放器同步。\n\n建议顺序：数据与输出 → 损失 → 一次更新 → 学习率 → 优化器 → 正则化 → 稳定性 → 评价。\n\n[训练速查与公式](docs/TRAINING_CHEATSHEET.md) · [完整目录](cs_ai_v2_index.md)\n\n' + [...micro, book.chapters[76]].map(c => `- [第 ${c.num} 讲：${c.title}](#chapter-${c.num})`).join('\n') + '\n\n---\n\n' + [...micro, book.chapters[76]].map(markdown).join('\n\n---\n\n'));

let index = generated + '# CS 与 AI：章节及知识点索引\n\n' +
  `共 ${book.stats.chapters} 讲、${book.stats.new_subsections} 个细讲小节、${book.stats.quiz_questions} 道口述题；正文里的导览段落另行保留。一个小节可比较多个概念，小节数不等于算法数。\n\n` +
  '[知识地图](docs/KNOWLEDGE_MAP.md) · [按英文查术语](docs/GLOSSARY.md) · [学习路线](docs/LEARNING_PATHS.md) · [训练速查](docs/TRAINING_CHEATSHEET.md) · [Hot 100 的 100 题映射](docs/LEETCODE_HOT100.md)\n\n## 快速入口\n\n' +
  '- [BCE 与输入契约](chapters/41.md)\n- [学习率与 SGD 数值例题](chapters/43.md)\n- [Batch、Step、Epoch 与尾批累积](chapters/44.md)\n- [随机森林](chapters/27.md)\n- [评价指标数值例题](chapters/38.md)\n\n## 领域导航\n\n';
const ranges = [['计算机系统', 1, 4], ['数据结构与算法', 5, 13], ['数据库、网络与分布式', 14, 20], ['机器学习与统计', 21, 39], ['深度学习与训练', 40, 51], ['LLM、检索与智能体', 52, 61], ['生成模型与多模态', 62, 64], ['强化学习', 65, 68], ['机器人、VLA 与世界模型', 69, 73], ['口述练习与复习', 74, 80], ['LeetCode Hot 100 算法思想', 81, 97]];
for (const [label, start, end] of ranges) index += `- [${label}：第 ${start}–${end} 讲](#chapter-${String(start).padStart(2, '0')})\n`;
for (const c of book.chapters) {
  index += `\n<a id="chapter-${c.num}"></a>\n\n## 第 ${c.num} 讲：${c.title}\n\n${c.group}\n\n[阅读本讲](chapters/${c.num}.md) · [完整讲稿](cs_ai_v2_full.md#chapter-${c.num})\n\n`;
  index += c.toc.length ? c.toc.map(s => `- [${s.title}](chapters/${c.num}.md#${s.anchor})`).join('\n') + '\n' : c.blocks[0].text + '\n';
}
emit('cs_ai_v2_index.md', index);

let hotGuide = generated + '# LeetCode Hot 100：主要算法思想\n\n' +
  `按[力扣官方 Hot 100 学习计划](${hot100.source})的 17 类、100 题整理，核对日期 **${hot100.checkedAt}**。新增第 81–97 讲，原章节编号保持稳定。解释与易错点为本仓库原创整理；官方分组用于定位，同一题可以使用多种算法。\n\n` +
  '阅读重点：**识别线索 → 状态或不变式 → 为什么可以移动／转移 → 复杂度 → 前提与反例**。题目链接用于查看完整约束、提交与练习。本页提供思想讲解与逐题映射；复杂度对应表中指定方案。\n\n' +
  '[完整索引](../cs_ai_v2_index.md) · [术语词典](GLOSSARY.md) · [播放器文件](../cs_ai_v2_audiobook.html)\n\n## 方法选择速查\n\n' +
  '| 看到什么结构 | 优先考虑 | 先确认什么 |\n| --- | --- | --- |\n' +
  '| 已见过的值、频次、配对 | 哈希表／集合 | 存下标还是计数，查询与写入谁先 |\n' +
  '| 有序两端的候选组合 | 对撞双指针 | 移动一侧能安全排除哪些候选 |\n' +
  '| 连续区间的频次合法性 | 滑动窗口 | 扩张、收缩怎样改变条件 |\n' +
  '| 含负数的区间和计数 | 前缀和 + 频次表 | 初始零前缀，先查再记 |\n' +
  '| 下一个更大／更小位置 | 单调栈 | 弹栈时答案是否已经确定 |\n' +
  '| 固定窗口的极值 | 单调双端队列 | 候选是否过期，端点操作是否高效 |\n' +
  '| 查排名边界或流式中位数 | 堆／快速选择 | 是否需要完整排序，是否允许修改输入 |\n' +
  '| 依赖关系、等权传播 | 拓扑排序／BFS | 有向环、多个起点、边权是否相同 |\n' +
  '| 枚举所有合法构造 | 回溯与剪枝 | 哪些状态要撤销，输出本身有多大 |\n' +
  '| 单调条件的边界 | 二分 | 区间约定、答案是否可在数组外边界 |\n' +
  '| 重复子问题的最优值／计数 | 动态规划 | 状态含义、初始化、依赖顺序 |\n' +
  '| 当前选择似乎已足够 | 贪心 | 排除或交换论证，新增约束是否破坏证明 |\n\n' +
  '符号约定：n、m 通常是输入长度；r、c 在矩阵题中为行列数；h 为树高，w 为最大层宽；σ 为字符集大小。各题另用的变量在易错点中注明。哈希时间按常用实现的期望复杂度，栈／队列的总线性时间按摊还分析；复杂度不把输出空间默认算作零。\n\n## 17 类思想导航\n\n| 官方分组 | 本仓库讲解 | 题数 |\n| --- | --- | --- |\n';
for (const c of hot100.categories) hotGuide += `| [${c.name}](#hot100-${c.chapter}) | [第 ${c.chapter} 讲](../chapters/${c.chapter}.md) | ${c.problems.length} |\n`;
hotGuide += '\n## 100 题逐题映射\n\n';
for (const c of hot100.categories) {
  hotGuide += `<a id="hot100-${c.chapter}"></a>\n\n### ${c.name}\n\n| 题号与官方入口 | 核心思路与讲解 | 时间 | 辅助空间 | 前提／易错点 |\n| --- | --- | --- | --- | --- |\n`;
  for (const p of c.problems) hotGuide += `| [${p.id} · ${p.title}](https://leetcode.cn/problems/${p.slug}/) | [${p.idea}](../chapters/${c.chapter}.md#chapter-${c.chapter}-section-${String(p.section).padStart(2,'0')}) | ${p.time} | ${p.space} | ${p.pitfall} |\n`;
  hotGuide += '\n';
}
hotGuide += '## 思想讲解正文\n\n' + book.chapters.filter(c=>c.hot100).map(markdown).join('\n\n---\n\n');
emit('docs/LEETCODE_HOT100.md', hotGuide);
emit('data/hot100-problems.json', JSON.stringify({source: hot100.source, checkedAt: hot100.checkedAt, categories: hot100.categories.map(c=>({name:c.name,chapter:c.chapter,problems:c.problems}))},null,2));

let dictionary = generated + '# 中英核心术语词典\n\n' +
  `${glossary.length} 个核心词条组，按英文排序。每条提供独立解释、易混点和正文入口；词条组可能包含多个相邻术语。全部细讲标题见[覆盖索引](../cs_ai_v2_index.md)。\n\n`;
const letters = [...new Set(glossary.map(g => g[0][0].toUpperCase()))];
dictionary += letters.map(l => `[${l}](#letter-${l.toLowerCase()})`).join(' · ') + '\n';
for (const letter of letters) {
  dictionary += `\n<a id="letter-${letter.toLowerCase()}"></a>\n\n## ${letter}\n\n`;
  for (const [en, zh, num, category, definition, boundary] of glossary.filter(g => g[0][0].toUpperCase() === letter)) {
    const c = book.chapters[num-1];
    const terms = en.split(' / ');
    const section = c.toc.find(s => terms.some(t => clean(s.title).toLowerCase().includes(t.toLowerCase())));
    dictionary += `### ${en}｜${zh}\n\n${definition}\n\n**易混点：** ${boundary}\n\n${category} · [第 ${c.num} 讲：${c.title}](../chapters/${c.num}.md${section ? '#' + section.anchor : ''})\n\n`;
  }
}
emit('docs/GLOSSARY.md', dictionary);
emit('docs/REFERENCES.md', generated + '# 参考资料\n\n' +
  '本页保留原稿全部参考资料，并补充本次训练说明所用文档。各讲结尾列出关联来源。资料来自官方文档、论文、课程或作者项目；列出来源不表示逐条内容均已重新审校。\n\n' +
  '本次核对日期：2026-10-16；重点核对训练接口、更新顺序及官方 Hot 100 的完整题单与分组。Hot 100 的解法说明为原创整理，逐题链接见专项笔记。PyTorch 的 stable 链接会随版本变化，复现实验请固定环境版本。通识模型示例不代表当前性能排名。\n\n' +
  book.sources.map(s => `<a id="source-${s.id}"></a>\n\n- **S${String(s.id).padStart(3, '0')}** [${s.title}](${s.url})\n  引用章节：${book.chapters.filter(c => c.source_ids.includes(s.id)).map(c => `[${c.num}](../chapters/${c.num}.md)`).join('、') || '延伸阅读'}`).join('\n\n'));

const json = JSON.stringify(book).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
const template = read('src/player.html');
if (template.split('__BOOK_DATA__').length !== 2) throw new Error('Expected one player data placeholder');
emit('cs_ai_v2_audiobook.html', template.replace('__BOOK_DATA__', () => json));
emit('data/stats.json', JSON.stringify(book.stats, null, 2));
emit('README.md', read('src/readme.md').replaceAll('{{VERSION}}', book.metadata.version).replaceAll('{{CHAPTERS}}', String(book.stats.chapters)).replaceAll('{{SUBSECTIONS}}', String(book.stats.new_subsections)).replaceAll('{{GLOSSARY}}', String(glossary.length)).replaceAll('{{SOURCES}}', String(book.sources.length)));

const check = process.argv.includes('--check');
const differences = [];
for (const [name, value] of outputs) {
  const file = path.join(root, name);
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== value) differences.push(name);
  } else {
    fs.mkdirSync(path.dirname(file), {recursive: true});
    fs.writeFileSync(file, value);
  }
}
if (differences.length) { console.error('Generated files out of date:', differences.join(', ')); process.exitCode = 1; }
else console.log(`${check ? 'Verified' : 'Generated'} ${outputs.size} files; ${book.stats.chapters} chapters, ${book.stats.new_subsections} detailed subsections, ${glossary.length} glossary groups.`);
